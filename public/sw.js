async function cacheInBatches(cache, urls, batchSize = 10) {
  for (let i = 0; i < urls.length; i += batchSize) {
    const batch = urls.slice(i, i + batchSize);
    await Promise.allSettled(
      batch.map(async (url) => {
        const existing = await cache.match(url);
        if (!existing) {
          const res = await fetch(url, { cache: "reload" });
          if (res && res.ok) {
            await cache.put(url, res);
          }
        }
      })
    );
  }
}

self.addEventListener("install", (event) => {
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE_NAME).then(async (cache) => {
      // Öncelikli görselleri (temel + 70 dizi kapağı + terapiler) hemen önbelleğe al
      await cacheInBatches(cache, PRIORITY_ASSETS, 12);
      // Karakter görsellerini arka planda kademeli olarak önbelleğe al
      cacheInBatches(cache, CHARACTER_ASSETS, 8).catch(() => {});
    })
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.map((key) => {
            if (key !== CACHE_NAME) {
              return caches.delete(key);
            }
          })
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;

  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  // Görseller (/series/, /characters/, /therapies/, .jpg, .png, .webp, .svg) için Cache-First (Önce Telefon Hafızası)
  const isImageAsset =
    url.pathname.startsWith("/series/") ||
    url.pathname.startsWith("/characters/") ||
    url.pathname.startsWith("/therapies/") ||
    /\.(jpg|jpeg|png|webp|svg|ico)$/i.test(url.pathname);

  if (isImageAsset) {
    event.respondWith(
      caches.open(CACHE_NAME).then(async (cache) => {
        const cached = await cache.match(url.pathname);
        if (cached) {
          return cached;
        }
        try {
          const networkRes = await fetch(event.request);
          if (networkRes && networkRes.ok) {
            cache.put(url.pathname, networkRes.clone());
          }
          return networkRes;
        } catch (err) {
          return cached || Response.error();
        }
      })
    );
    return;
  }

  // Sayfa geçişleri (navigate) için Network-First, çevrimdışıysa Cache
  if (event.request.mode === "navigate") {
    event.respondWith(
      fetch(event.request)
        .then((res) => {
          if (res && res.ok) {
            const clone = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(url.pathname, clone));
          }
          return res;
        })
        .catch(async () => {
          const cache = await caches.open(CACHE_NAME);
          return (await cache.match(url.pathname)) || (await cache.match("/"));
        })
    );
  }
});
